"""Read-only inspection of the raw NASA data in Pseudo_DataKeep/.

Prints, for every CSV: columns, dtypes, row count, empty values, 5 sample rows,
top values of text columns and unit hints. For every PDF: page count, how much
text is extractable, tables per page, headings, and pages that mention CSV columns.

Usage:  python -I scripts/ingest/inspect.py [--out docs/inspect_output.md]
Nothing in Pseudo_DataKeep/ is ever written.
(-I is needed: this file name shadows the stdlib "inspect" module otherwise.)
"""
from __future__ import annotations

import argparse
import io
import re
import sys
from pathlib import Path

import pandas as pd
import pdfplumber
import pymupdf

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "Pseudo_DataKeep"
INVESTIGATIONS = ["ACME", "CFI", "SPICE"]
UNIT_RE = re.compile(r"\(([^)]+)\)|_(pct|psi|kpa|atm|mm|cm_s|cms|s|ms|k|c|mg|ul|um)$", re.I)


def inspect_csv(path: Path, out: io.StringIO) -> list[str]:
    df = pd.read_csv(path)
    out.write(f"\n### {path.relative_to(ROOT).as_posix()}\n\n")
    out.write(f"Rows: {len(df)} · Columns: {len(df.columns)}\n\n")
    out.write("| column | dtype | empty | unique | unit hint | example |\n|---|---|---|---|---|---|\n")
    for col in df.columns:
        s = df[col]
        hint = UNIT_RE.search(str(col))
        unit = (hint.group(1) or hint.group(2)) if hint else ""
        ex = s.dropna().iloc[0] if s.notna().any() else ""
        out.write(
            f"| {col} | {s.dtype} | {int(s.isna().sum())} | {s.nunique(dropna=True)} | {unit} | {str(ex)[:40]} |\n"
        )
    out.write("\nSample rows:\n\n```\n")
    out.write(df.head(5).to_string(max_colwidth=30))
    out.write("\n```\n")
    num = df.select_dtypes("number")
    if not num.empty:
        out.write("\nNumeric ranges:\n\n```\n")
        out.write(num.describe().T[["count", "min", "max", "mean"]].to_string())
        out.write("\n```\n")
    for col in df.select_dtypes(exclude="number").columns:
        top = df[col].value_counts(dropna=True).head(8)
        out.write(f"\nTop values of `{col}`: " + ", ".join(f"{k} ({v})" for k, v in top.items()) + "\n")
    return [str(c) for c in df.columns]


def inspect_pdf(path: Path, columns: list[str], out: io.StringIO) -> None:
    out.write(f"\n### {path.relative_to(ROOT).as_posix()}\n\n")
    doc = pymupdf.open(path)
    out.write(f"Pages: {doc.page_count}\n\n")
    headings: list[str] = []
    col_pages: dict[str, list[int]] = {c: [] for c in columns}
    with pdfplumber.open(path) as pdf:
        out.write("| page | chars | tables | first line |\n|---|---|---|---|\n")
        for i, page in enumerate(pdf.pages, start=1):
            text = page.extract_text() or ""
            tables = page.extract_tables() or []
            first = text.strip().splitlines()[0][:70] if text.strip() else "(no text)"
            out.write(f"| {i} | {len(text)} | {len(tables)} | {first} |\n")
            low = text.lower()
            for c in columns:
                key = c.lower()
                variants = {key, key.replace("_", " ")}
                if any(v in low for v in variants):
                    col_pages[c].append(i)
    for pno in range(doc.page_count):
        for block in doc[pno].get_text("dict")["blocks"]:
            for line in block.get("lines", []):
                for span in line.get("spans", []):
                    t = span["text"].strip()
                    if t and (span["size"] >= 12.5 or ("Bold" in span["font"] and len(t) < 80 and span["size"] >= 10.5)):
                        headings.append(f"p{pno + 1}: {t}")
    out.write("\nHeadings:\n\n")
    seen = set()
    for h in headings:
        if h not in seen:
            seen.add(h)
            out.write(f"- {h}\n")
    out.write("\nPages mentioning CSV columns:\n\n")
    for c, pages in col_pages.items():
        out.write(f"- `{c}`: {', '.join(map(str, sorted(set(pages)))) or 'not mentioned'}\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=None)
    args = ap.parse_args()
    out = io.StringIO()
    out.write("# Raw data inspection (generated by scripts/ingest/inspect.py)\n")
    for inv in INVESTIGATIONS:
        folder = RAW / inv
        out.write(f"\n## {inv}\n")
        csv = folder / f"{inv}_Experimental_Table.csv"
        cols = inspect_csv(csv, out) if csv.exists() else []
        for kind in ["Engineering_Doc", "Report"]:
            pdf = folder / f"{inv}_{kind}.pdf"
            if pdf.exists():
                inspect_pdf(pdf, cols, out)
            else:
                out.write(f"\nMISSING: {pdf.name}\n")
    text = out.getvalue()
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"wrote {args.out}")
    else:
        sys.stdout.reconfigure(encoding="utf-8")
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
